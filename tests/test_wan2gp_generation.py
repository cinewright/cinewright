"""The generation path end to end on a fake Wan2GP (#5): request, routing, worker, Wan2GP task and provenance.

The core runs on uvicorn with the bundled registry (the four MVP models), installs are rows of `installed_models`
(`mark_installed`), and the local worker is the real worker loop with the Wan2GP adapter, run in this process over the
fake `shared.api` and `wgp` of `test_wan2gp_adapter`, on a checkout that holds exactly the installed files.
"""

from __future__ import annotations

import contextlib
import socket
import sys
import threading
import time
from collections.abc import Callable, Iterator
from pathlib import Path

import httpx
import pytest
import uvicorn
from conftest import PNG, fake_detect, mark_installed, stage
from conftest import no_network as no_downloads
from test_wan2gp_adapter import FakeSession, fake_wan2gp, install, provision_ffmpeg

from cinewright.api.schemas import ClientKind, DataClass, JobRequest, JobState
from cinewright.app import create_app
from cinewright.config import Config
from cinewright.core.core import Core
from cinewright.core.modelstore import plan_files
from cinewright.core.registry import Registry
from cinewright_worker.client import WorkerClient
from cinewright_worker.engines.wan2gp import Wan2GPAdapter
from cinewright_worker.loop import WorkerLoop

LTX, LTX_TYPE = "ltx-2.3-distilled-22b", "ltx2_22B_distilled"
TIMEOUT_S = 15


def wait_for(predicate: Callable[[], object], what: str) -> None:
    deadline = time.monotonic() + TIMEOUT_S
    while not predicate():
        assert time.monotonic() < deadline, f"timed out waiting for {what}"
        time.sleep(0.02)


@pytest.fixture
def served(home: Path) -> Iterator[Core]:
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", 0))
    core = Core(
        Config(home=home, port=sock.getsockname()[1]),
        registry=Registry.load(),
        detect=fake_detect,
        download_transport=httpx.MockTransport(no_downloads),
    )
    server = uvicorn.Server(uvicorn.Config(create_app(core), log_config=None, timeout_graceful_shutdown=2))
    thread = threading.Thread(target=server.run, kwargs={"sockets": [sock]}, daemon=True, name="uvicorn")
    thread.start()
    wait_for(lambda: server.started or not thread.is_alive(), "uvicorn to start")
    assert thread.is_alive(), "uvicorn stopped during startup"
    try:
        yield core
    finally:
        server.should_exit = True
        thread.join(timeout=TIMEOUT_S)
        core.close()
        sock.close()
        assert not thread.is_alive(), "uvicorn did not stop"


@contextlib.contextmanager
def wan2gp_worker(core: Core, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, quant: str) -> Iterator[list[FakeSession]]:
    """The real worker loop with the Wan2GP adapter on a fake checkout that holds exactly LTX-2.3 in `quant`, which
    the core's model store records as installed. Wan2GP's own default quantization is bf16 here."""
    sessions = fake_wan2gp(monkeypatch)
    wgp = sys.modules["wgp"]
    wgp.transformer_quantization = wgp.server_config["transformer_quantization"] = "bf16"
    root = tmp_path / "wan2gp"
    provision_ffmpeg(root)
    install(root, LTX_TYPE, quant)
    mark_installed(core, (LTX, quant))
    adapter = Wan2GPAdapter(root=str(root), data_dir=str(tmp_path / "data"))
    loop = WorkerLoop(adapter, WorkerClient(core.config.base_url, timeout=5), core.enrollment_token, lease_wait=0.5, poll_interval=0.01)
    worker = threading.Thread(target=loop.run, daemon=True, name="worker")
    worker.start()
    try:
        yield sessions
    finally:
        loop.stop.set()
        worker.join(timeout=TIMEOUT_S)
    assert not worker.is_alive()


def finish(sessions: list[FakeSession], tmp_path: Path, name: str, check: Callable[[dict], None] = lambda _: None) -> dict:
    """Wait for the job to reach Wan2GP, run `check` on the task's settings while the job runs, let Wan2GP produce
    the file `name` and return the settings."""
    wait_for(lambda: sessions and sessions[0].submitted, "the job to reach Wan2GP")
    settings, handle = sessions[0].submitted[0]
    check(settings)
    produced = tmp_path / "engine" / name
    produced.parent.mkdir()
    produced.write_bytes(b"generated bytes")
    handle.finish(success=True, files=[str(produced)])
    return settings


def test_an_i2v_job_runs_the_installed_int8_and_its_provenance_records_it(served, tmp_path, monkeypatch):
    core = served
    with wan2gp_worker(core, tmp_path, monkeypatch, "int8") as sessions:  # only int8, although bf16 comes first
        image = core.add_asset(stage(core, PNG), "image/png", DataClass.PRIVATE).sha256
        extra = {"denoising_strength": 0.7, "guidance_phases": 1}
        request = JobRequest.model_validate(
            {"capability": "i2v", "prompt": "The lighthouse beam sweeps", "model": LTX, "inputs": [image], "params": {"extra": extra}}
        )
        wait_for(lambda: core.estimate(request).feasible, "the worker to register")
        job = core.submit_job(request, ClientKind.UI, None)
        assert job.route.quant == "int8"

        settings = finish(sessions, tmp_path, "lighthouse.mp4")  # as Wan2GP runs it
        assert settings["overrides"] == "transformer_quantization='int8'"
        assert (settings["guidance_phases"], settings["denoising_strength"]) == (1, 1.0)
        assert (settings["model_type"], settings["image_start"].endswith(f"{image}.png")) == (LTX_TYPE, True)
        wait_for(lambda: core.get_job(job.id).state == JobState.SUCCEEDED, "the job to succeed")

    output = core.get_asset(core.get_job(job.id).outputs[0])
    assert output.media_type == "video/mp4"
    provenance = output.provenance
    assert (provenance.model.quant, provenance.model.engine_version) == ("int8", "19.292")
    # The int8 transformer, then the shared files with the host's text encoder variant.
    planned = plan_files(core.registry, LTX, "int8", "int8")
    assert provenance.model.file_sha256 == [file.sha256 for file in planned]
    assert provenance.model.file_sha256[0] == core.registry.get(LTX).quantizations[1].files[0].sha256
    # Registry defaults fill the parameters. Of the extras, Wan2GP runs only guidance_phases as asked: it resets
    # denoising_strength without a control image, so the worker does not report it.
    assert provenance.params.model_dump() == {
        "resolution": "1280x704",
        "steps": 8,
        "frames": 241,
        "fps": 24,
        "guidance": None,
        "extra": {"guidance_phases": 1},
    }


def test_a_t2i_job_pinned_to_ltx_runs_in_image_mode_and_returns_a_jpeg(served, tmp_path, monkeypatch):
    core = served
    with wan2gp_worker(core, tmp_path, monkeypatch, "bf16") as sessions:
        # The registry fills fps 24 (and the request asks for 121 frames); image mode must not receive either.
        request = JobRequest.model_validate(
            {"capability": "t2i", "prompt": "A lighthouse at dusk", "model": LTX, "params": {"frames": 121}}
        )
        wait_for(lambda: core.estimate(request).feasible, "the worker to register")
        job = core.submit_job(request, ClientKind.UI, None)
        assert (job.route.model_id, job.route.quant) == (LTX, "bf16")

        settings = finish(sessions, tmp_path, "lighthouse.jpg")  # image_output_codec jpeg_95
        assert (settings["model_type"], settings["image_mode"]) == (LTX_TYPE, 1)
        assert (settings["video_length"], settings["force_fps"], settings["duration_seconds"]) == (241, "", 0)  # Wan2GP's
        assert settings["overrides"] == "transformer_quantization='bf16'"
        wait_for(lambda: core.get_job(job.id).state == JobState.SUCCEEDED, "the job to succeed")

    output = core.get_asset(core.get_job(job.id).outputs[0])
    assert output.media_type == "image/jpeg"
    params = output.provenance.params
    assert (params.resolution, params.steps, params.frames, params.fps, params.extra) == ("1280x704", 8, None, None, {})


def test_an_i2i_job_on_ltx_hands_its_image_to_wan2gp_as_the_control_image(served, tmp_path, monkeypatch):
    core = served
    with wan2gp_worker(core, tmp_path, monkeypatch, "int8") as sessions:
        image = core.add_asset(stage(core, PNG), "image/png", DataClass.PRIVATE).sha256
        job_params = {"extra": {"denoising_strength": 0.6}}
        request = JobRequest.model_validate(
            {"capability": "i2i", "prompt": "The lighthouse at night", "model": LTX, "inputs": [image], "params": job_params}
        )
        wait_for(lambda: core.estimate(request).feasible, "the worker to register")
        job = core.submit_job(request, ClientKind.UI, None)

        def the_input_is_the_control_image(settings: dict) -> None:
            # The worker's download of the input, as an absolute path: Wan2GP generates from its own root.
            guide = Path(settings["image_guide"])
            assert (guide.is_absolute(), guide.name, guide.read_bytes()) == (True, f"{image}.png", PNG)

        settings = finish(sessions, tmp_path, "lighthouse.jpg", the_input_is_the_control_image)
        assert (settings["model_type"], settings["image_mode"], settings["video_prompt_type"]) == (LTX_TYPE, 1, "VG")
        assert settings["image_start"] is None and "S" not in settings["image_prompt_type"]
        assert (settings["denoising_strength"], settings["overrides"]) == (0.6, "transformer_quantization='int8'")
        wait_for(lambda: core.get_job(job.id).state == JobState.SUCCEEDED, "the job to succeed")

    output = core.get_asset(core.get_job(job.id).outputs[0])
    assert output.media_type == "image/jpeg"
    provenance = output.provenance
    assert (provenance.parents, provenance.model.quant) == ([image], "int8")
    params = provenance.params
    assert (params.frames, params.fps, params.extra) == (None, None, {"denoising_strength": 0.6})
