// Generates src/styles/tokens.css from ../design/tokens.json.
//
// Every token becomes a CSS custom property named exactly like the token (--surface-000, --space-4,
// --radius-lg, --shadow-overlay, --font-sans, ...). Dark is the default theme on :root; light applies
// under :root[data-theme="light"] and, when no explicit data-theme="dark" is set, under
// @media (prefers-color-scheme: light). Aliases such as "{accent}" resolve within the same theme.
// Text styles become shorthand variables (--text-body) and classes (.text-body).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DEFAULT_THEME = 'dark';
export const ALTERNATE_THEME = 'light';

const ALIAS = /^\{([a-z0-9-]+)\}$/;

function isThemed(value) {
  return value !== null && typeof value === 'object';
}

/** Resolve "{name}" references for one theme; throws on unknown names and cycles. */
function resolveTheme(raw, theme) {
  const resolved = new Map();
  const visit = (name, trail) => {
    if (resolved.has(name)) return resolved.get(name);
    if (!raw.has(name)) throw new Error(`Unknown token "${name}" referenced from "${trail.at(-1)}"`);
    if (trail.includes(name)) throw new Error(`Alias cycle: ${[...trail, name].join(' -> ')}`);
    const entry = raw.get(name);
    const value = isThemed(entry) ? entry[theme] : entry;
    if (typeof value !== 'string') throw new Error(`Token "${name}" has no value for theme "${theme}"`);
    const alias = ALIAS.exec(value);
    const result = alias ? visit(alias[1], [...trail, name]) : value;
    resolved.set(name, result);
    return result;
  };
  for (const name of raw.keys()) visit(name, []);
  return resolved;
}

/**
 * Turn the design tokens into resolved sets.
 * Returns { base: Map, themes: { dark: Map, light: Map }, textStyles: Array }.
 * `base` holds values that do not change with the theme; `themes` hold the themed ones.
 */
export function buildTokenSets(tokens) {
  const themeIds = tokens.color.themes.map((t) => t.id);
  for (const id of [DEFAULT_THEME, ALTERNATE_THEME]) {
    if (!themeIds.includes(id)) throw new Error(`tokens.json lacks the "${id}" theme`);
  }

  const raw = new Map();
  for (const group of [tokens.color.tokens, tokens.shadow.tokens, tokens.spacing.tokens, tokens.radius.tokens]) {
    for (const token of group) {
      if (raw.has(token.name)) throw new Error(`Duplicate token "${token.name}"`);
      raw.set(token.name, token.value);
    }
  }

  const perTheme = Object.fromEntries([DEFAULT_THEME, ALTERNATE_THEME].map((id) => [id, resolveTheme(raw, id)]));
  const base = new Map();
  const themes = { [DEFAULT_THEME]: new Map(), [ALTERNATE_THEME]: new Map() };
  for (const [name, value] of raw) {
    const themed = isThemed(value) || [DEFAULT_THEME, ALTERNATE_THEME].some((id) => perTheme[id].get(name) !== perTheme[DEFAULT_THEME].get(name));
    if (themed) {
      for (const id of [DEFAULT_THEME, ALTERNATE_THEME]) themes[id].set(name, perTheme[id].get(name));
    } else {
      base.set(name, perTheme[DEFAULT_THEME].get(name));
    }
  }

  for (const [family, stack] of Object.entries(tokens.type.families)) base.set(`font-${family}`, stack);

  const textStyles = [];
  for (const group of tokens.type.groups) {
    if (!(group.family in tokens.type.families)) throw new Error(`Unknown font family "${group.family}" in group "${group.name}"`);
    for (const style of group.styles) {
      textStyles.push({
        name: style.name,
        family: group.family,
        font: `${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${group.family})`,
        letterSpacing: style.letterSpacing ?? null,
        tabular: group.family === 'mono',
      });
    }
  }
  for (const style of textStyles) {
    base.set(`text-${style.name}`, style.font);
    if (style.letterSpacing) base.set(`text-${style.name}-letter-spacing`, style.letterSpacing);
  }

  return { base, themes, textStyles };
}

function declarations(map, indent) {
  return [...map].map(([name, value]) => `${indent}--${name}: ${value};`).join('\n');
}

/** Render the CSS text. Deterministic: token order follows tokens.json. */
export function generateTokensCss(tokens) {
  const { base, themes, textStyles } = buildTokenSets(tokens);
  const dark = themes[DEFAULT_THEME];
  const light = themes[ALTERNATE_THEME];
  const classes = textStyles.map((style) => {
    const lines = [`  font: var(--text-${style.name});`];
    if (style.letterSpacing) lines.push(`  letter-spacing: var(--text-${style.name}-letter-spacing);`);
    if (style.tabular) lines.push('  font-variant-numeric: tabular-nums;');
    return `.text-${style.name} {\n${lines.join('\n')}\n}`;
  });
  return [
    '/* Generated by web/scripts/gen-tokens.mjs from design/tokens.json. Do not edit; run "npm run gen:tokens". */',
    '',
    ':root {',
    '  color-scheme: dark;',
    declarations(base, '  '),
    declarations(dark, '  '),
    '}',
    '',
    ':root[data-theme="light"] {',
    '  color-scheme: light;',
    declarations(light, '  '),
    '}',
    '',
    '@media (prefers-color-scheme: light) {',
    '  :root:not([data-theme="dark"]) {',
    '    color-scheme: light;',
    declarations(light, '    '),
    '  }',
    '}',
    '',
    ...classes.flatMap((c) => [c, '']),
  ].join('\n');
}

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = resolve(here, '../../design/tokens.json');
export const TOKENS_CSS = resolve(here, '../src/styles/tokens.css');

export function loadTokens(path = TOKENS_JSON) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeFileSync(TOKENS_CSS, generateTokensCss(loadTokens()), 'utf8');
  console.log(`Wrote ${TOKENS_CSS}`);
}
